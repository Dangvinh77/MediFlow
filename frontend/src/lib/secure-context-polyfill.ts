/**
 * Browsers expose crypto.randomUUID and crypto.subtle only in secure contexts (HTTPS or
 * localhost), so both are undefined when the demo is opened by LAN IP over plain HTTP.
 * getRandomValues stays available, which keeps generated ids cryptographically random.
 * Native implementations are never replaced.
 */

