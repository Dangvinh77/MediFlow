const rotr = (value: number, bits: number) => (value >>> bits) | (value << (32 - bits));

function sha256(message: Uint8Array): ArrayBuffer {
  const paddedLength = (((message.length + 8) >>> 6) + 1) * 64;
  const padded = new Uint8Array(paddedLength);
  padded.set(message);
  padded[message.length] = 0x80;
  const view = new DataView(padded.buffer);
  view.setUint32(paddedLength - 8, Math.floor(message.length / 0x20000000));
  view.setUint32(paddedLength - 4, message.length << 3);

  const hash = new Uint32Array([
    0x6a09e667, 0xbb67ae85, 0x3c6ef372, 0xa54ff53a, 0x510e527f, 0x9b05688c, 0x1f83d9ab, 0x5be0cd19,
  ]);
  const words = new Uint32Array(64);

  for (let block = 0; block < paddedLength; block += 64) {
    for (let i = 0; i < 16; i++) words[i] = view.getUint32(block + i * 4);
    for (let i = 16; i < 64; i++) {
      const w15 = words[i - 15];
      const w2 = words[i - 2];
      const s0 = rotr(w15, 7) ^ rotr(w15, 18) ^ (w15 >>> 3);
      const s1 = rotr(w2, 17) ^ rotr(w2, 19) ^ (w2 >>> 10);
      words[i] = words[i - 16] + s0 + words[i - 7] + s1;
    }

    let [a, b, c, d, e, f, g, h] = hash;
    for (let i = 0; i < 64; i++) {
      const s1 = rotr(e, 6) ^ rotr(e, 11) ^ rotr(e, 25);
      const choice = (e & f) ^ (~e & g);
      const t1 = (h + s1 + choice + ROUND_CONSTANTS[i] + words[i]) | 0;
      const s0 = rotr(a, 2) ^ rotr(a, 13) ^ rotr(a, 22);
      const majority = (a & b) ^ (a & c) ^ (b & c);
      const t2 = (s0 + majority) | 0;
      h = g;
      g = f;
      f = e;
      e = (d + t1) | 0;
      d = c;
      c = b;
      b = a;
      a = (t1 + t2) | 0;
    }

    [a, b, c, d, e, f, g, h].forEach((value, i) => { hash[i] += value; });
  }

  const output = new DataView(new ArrayBuffer(32));
  hash.forEach((value, i) => output.setUint32(i * 4, value));
  return output.buffer;
}

function toBytes(data: BufferSource): Uint8Array {
  return ArrayBuffer.isView(data)
    ? new Uint8Array(data.buffer, data.byteOffset, data.byteLength)
    : new Uint8Array(data);
}

function randomUuid(source: Crypto): ReturnType<Crypto["randomUUID"]> {
  const bytes = source.getRandomValues(new Uint8Array(16));
  bytes[6] = (bytes[6] & 0x0f) | 0x40; // version 4
  bytes[8] = (bytes[8] & 0x3f) | 0x80; // RFC 4122 variant
  const hex = Array.from(bytes, (byte) => byte.toString(16).padStart(2, "0")).join("");
  return `${hex.slice(0, 8)}-${hex.slice(8, 12)}-${hex.slice(12, 16)}-${hex.slice(16, 20)}-${hex.slice(20)}`;
}

export function installSecureContextPolyfill(target: Crypto = globalThis.crypto) {
  if (typeof target.randomUUID !== "function") {
    Object.defineProperty(target, "randomUUID", { configurable: true, value: () => randomUuid(target) });
  }
  if (!target.subtle) {
    const digest = async (algorithm: AlgorithmIdentifier, data: BufferSource) => {
      const name = typeof algorithm === "string" ? algorithm : algorithm.name;
      if (name.toUpperCase() !== "SHA-256") throw new Error(`Unsupported digest algorithm: ${name}`);
      return sha256(toBytes(data));
    };
    Object.defineProperty(target, "subtle", { configurable: true, value: { digest } });
  }
}
