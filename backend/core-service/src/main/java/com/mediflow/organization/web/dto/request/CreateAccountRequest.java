package com.mediflow.organization.web.dto.request;

import java.util.UUID;

import com.mediflow.organization.domain.model.Role;

import jakarta.validation.constraints.NotBlank;
import jakarta.validation.constraints.NotNull;
import jakarta.validation.constraints.Size;
import jakarta.validation.constraints.Email;

public record CreateAccountRequest(
        @NotBlank(message = "Username must not be blank")
        @Email(message = "A valid email address is required")
        @Size(max = 254, message = "Email must not exceed 254 characters")
        String username,

        @jakarta.validation.constraints.Null(message = "Temporary passwords are generated by the system")
        String password,

        UUID staffId,

        UUID patientId,

        @NotNull(message = "Role must not be null")
        Role role,
        boolean replaceActiveAccount) {

    public CreateAccountRequest(String username, String password, UUID staffId, UUID patientId, Role role) {
        this(username, password, staffId, patientId, role, false);
    }
}
