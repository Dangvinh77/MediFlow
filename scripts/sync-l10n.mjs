import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { resolve } from "node:path";

const root = fileURLToPath(new URL("../", import.meta.url));
const english = JSON.parse(readFileSync(resolve(root, "frontend/src/lib/l10n/en.json"), "utf8"));
const vietnamese = JSON.parse(readFileSync(resolve(root, "frontend/src/lib/l10n/vi.json"), "utf8"));
const keys = Object.keys(english).sort();
if (JSON.stringify(keys) !== JSON.stringify(Object.keys(vietnamese).sort())) throw new Error("Vietnamese and English catalogs must have identical keys");
for (const key of keys) {
  const slots = value => [...value.matchAll(/\{\d+\}/g)].map(match => match[0]).sort().join(",");
  if (!english[key].trim() || slots(english[key]) !== slots(vietnamese[key])) throw new Error(`Invalid translation slots: ${key}`);
}
const quote = value => JSON.stringify(value).replaceAll("$", "\\$");
for (const [language, messages] of [["en", english], ["vi", vietnamese]]) {
  // Match dart format: long entries use a line break before their value.
  const lines = keys.map(key => `  ${quote(key)}: ${quote(messages[key])},`);
  const output = `// Generated by node scripts/sync-l10n.mjs. Edit frontend/src/lib/l10n/*.json.\n// Both clients use the same static catalog; no online translation at runtime.\nconst messages${language === "en" ? "En" : "Vi"} = <String, String>{\n${lines.join("\n")}\n};\n`;
  writeFileSync(resolve(root, `mobile/lib/core/l10n/messages_${language}.dart`), output);
}
console.log(`Synchronized ${keys.length} Vietnamese/English messages for web and mobile.`);
